function getPlayerById(playerId) {
    if (!playerId) return null;
    for (const clubKey in TEAMS_DATA) {
        const p = TEAMS_DATA[clubKey].players.find(x => x.id === playerId);
        if (p) {
            return {
                ...p,
                teamInfo: TEAMS_DATA[clubKey]
            };
        }
    }
    return null;
}

/**
 * Helper: Get all players for a match fixture between two clubs
 */
function getMatchPlayers(homeClubId, awayClubId) {
    const homeClub = TEAMS_DATA[homeClubId];
    const awayClub = TEAMS_DATA[awayClubId];
    const homePlayers = homeClub ? homeClub.players.map(p => ({ ...p, teamInfo: homeClub })) : [];
    const awayPlayers = awayClub ? awayClub.players.map(p => ({ ...p, teamInfo: awayClub })) : [];
    return [...homePlayers, ...awayPlayers];
}